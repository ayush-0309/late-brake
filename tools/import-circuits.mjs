// Converts real circuit outlines (GeoJSON, lon/lat) into local meter
// coordinates for the game: node tools/import-circuits.mjs
//
// Source data: https://github.com/bacinger/f1-circuits (MIT, © Tomislav Bacinger)

import { readFileSync, writeFileSync } from 'node:fs';

const IDS = ['at-1969', 'it-1922', 'gb-1948', 'be-1925', 'mc-1929', 'br-1940'];
const R = 6371000;

const geo = JSON.parse(readFileSync(new URL('../data/f1-circuits.geojson', import.meta.url)));
const out = [];

for (const id of IDS) {
  const f = geo.features.find((f) => f.properties.id === id);
  if (!f) throw new Error(`Circuit ${id} not in dataset`);
  let coords = f.geometry.coordinates;
  const [a, b] = [coords[0], coords.at(-1)];
  if (a[0] === b[0] && a[1] === b[1]) coords = coords.slice(0, -1);

  // Equirectangular projection around the circuit's own latitude: plenty
  // accurate over a few kilometers. Screen y points down, so north is up.
  const lat0 = (coords.reduce((s, p) => s + p[1], 0) / coords.length) * (Math.PI / 180);
  const lon0 = coords[0][0], la0 = coords[0][1];
  const points = coords.map(([lon, lat]) => [
    Math.round(R * (lon - lon0) * (Math.PI / 180) * Math.cos(lat0) * 10) / 10,
    Math.round(-R * (lat - la0) * (Math.PI / 180) * 10) / 10,
  ]);

  out.push({ id, name: f.properties.Name, location: f.properties.Location, length: f.properties.length, points });
}

const body = `// Generated by tools/import-circuits.mjs — do not edit by hand.
// Circuit outlines from https://github.com/bacinger/f1-circuits (MIT, © Tomislav Bacinger).
// Meters, x east, y south, first point on the start/finish line, in race direction.

export const CIRCUITS = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../src/circuits.js', import.meta.url), body);
